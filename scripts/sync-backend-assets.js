#!/usr/bin/env node
// Copies the backend's clinical/ML artefacts into app/assets/rules/ (ADR 010: the app never
// imports ../backend at runtime; it bundles a copy that a test keeps in sync).
//
//   node scripts/sync-backend-assets.js          # write assets/rules/*
//   node scripts/sync-backend-assets.js --check  # exit 1 if the bundled copy is stale
//
// Sources (owned by the backend engineer, read-only here):
//   backend/triage/dist/rules.json          + its line in backend/triage/dist/SHA256SUMS
//   backend/ml/detection/quality_gate.yaml  (converted to JSON; the app has no YAML parser)
'use strict';
/* global __dirname, Buffer */

const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');

const appRoot = path.resolve(__dirname, '..');
const defaultBackendRoot = path.resolve(appRoot, '..', 'backend');
const outDir = path.join(appRoot, 'assets', 'rules');

const sha256 = (buf) => crypto.createHash('sha256').update(buf).digest('hex');

// Minimal YAML reader for the flat config files the backend ships (nested mappings of scalars,
// two-space indentation, comments). Anything else throws, so a format change fails loudly
// instead of being misread.
function parseSimpleYaml(text) {
  const root = {};
  const stack = [{ indent: -1, node: root }];
  text.split(/\r?\n/).forEach((raw, i) => {
    const line = raw.replace(/(^|\s)#.*$/, '').replace(/\s+$/, '');
    if (!line.trim()) return;
    const indent = line.length - line.trimStart().length;
    const m = /^([A-Za-z_][\w-]*):(?:\s+(.*))?$/.exec(line.trim());
    if (indent % 2 !== 0 || !m) throw new Error(`unsupported YAML at line ${i + 1}: ${raw}`);
    while (stack.length > 1 && indent <= stack[stack.length - 1].indent) stack.pop();
    const parent = stack[stack.length - 1].node;
    const [, key, value] = m;
    if (value === undefined) {
      parent[key] = {};
      stack.push({ indent, node: parent[key] });
    } else {
      parent[key] = parseScalar(value, i + 1);
    }
  });
  return root;
}

function parseScalar(value, lineNo) {
  if (value === 'null' || value === '~') return null;
  if (value === 'true') return true;
  if (value === 'false') return false;
  if (/^-?\d+$/.test(value)) return Number.parseInt(value, 10);
  if (/^-?\d+\.\d+$/.test(value)) return Number.parseFloat(value);
  const quoted = /^(['"])(.*)\1$/.exec(value);
  if (quoted) return quoted[2];
  if (/^[[{|>&*!-]/.test(value)) throw new Error(`unsupported YAML value at line ${lineNo}: ${value}`);
  return value;
}

/** Returns { relativePath: fileContents } for everything under assets/rules/. */
function buildAssets(backendRoot = defaultBackendRoot) {
  const rulesPath = path.join(backendRoot, 'triage', 'dist', 'rules.json');
  const sumsPath = path.join(backendRoot, 'triage', 'dist', 'SHA256SUMS');
  const gatePath = path.join(backendRoot, 'ml', 'detection', 'quality_gate.yaml');

  const rulesBuf = fs.readFileSync(rulesPath);
  const rulesSha = sha256(rulesBuf);
  const sums = fs.readFileSync(sumsPath, 'utf8');
  const listed = sums
    .split(/\r?\n/)
    .map((l) => l.trim().split(/\s+\*?/))
    .find(([, name]) => name === 'rules.json');
  if (!listed || listed[0] !== rulesSha) {
    throw new Error('backend/triage/dist/rules.json does not match its SHA256SUMS entry');
  }
  const rules = JSON.parse(rulesBuf.toString('utf8'));

  const gateText = fs.readFileSync(gatePath, 'utf8');
  const gate = parseSimpleYaml(gateText);

  const sources = {
    note: 'GENERATED by scripts/sync-backend-assets.js. Do not edit; change the backend source and re-run.',
    triage_rules: {
      source: 'backend/triage/dist/rules.json',
      sha256: rulesSha,
      version: rules.version,
      status: rules.status,
    },
    quality_gate: {
      source: 'backend/ml/detection/quality_gate.yaml',
      // LF-normalised so a CRLF checkout on Windows does not look stale.
      sha256: sha256(Buffer.from(gateText.replace(/\r\n/g, '\n'), 'utf8')),
      version: gate.version,
      status: gate.status,
    },
  };

  return {
    // Byte-for-byte copy so the SHA-256 stays verifiable against SHA256SUMS / the manifest.
    'triage-rules.json': rulesBuf.toString('utf8'),
    'quality-gate.json': `${JSON.stringify(gate, null, 2)}\n`,
    'SOURCES.json': `${JSON.stringify(sources, null, 2)}\n`,
  };
}

function main(argv) {
  const check = argv.includes('--check');
  const assets = buildAssets();
  const stale = [];
  for (const [name, contents] of Object.entries(assets)) {
    const target = path.join(outDir, name);
    const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
    if (current === contents) continue;
    stale.push(name);
    if (!check) {
      fs.mkdirSync(outDir, { recursive: true });
      fs.writeFileSync(target, contents);
    }
  }
  if (check && stale.length) {
    console.error(`assets/rules is stale: ${stale.join(', ')}. Run: node scripts/sync-backend-assets.js`);
    return 1;
  }
  console.log(stale.length ? `updated: ${stale.join(', ')}` : 'assets/rules is up to date');
  return 0;
}

module.exports = { buildAssets, parseSimpleYaml };

if (require.main === module) process.exit(main(process.argv.slice(2)));
